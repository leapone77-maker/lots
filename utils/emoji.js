// ② 快捷词表：独立成词/句尾的常用词 → 前面加 emoji
//    用正则边界匹配，避免误伤正常句子里的词（如"加油站"不会被改）。
//    规则：{ re: 正则, emoji: '💪' }，替换时在匹配词前插入 emoji。
const WORD_EMOJI = [
  { re: /(^|[\s，。！、！?])(加油)(?=[\s，。！？!?]|$)/g, emoji: '💪' },
  { re: /(^|[\s，。！、！?])(谢谢)(?=[\s，。！？!?]|$)/g, emoji: '🙏' },
  { re: /(^|[\s，。！、！?])(生日快乐)(?=[\s，。！？!?]|$)/g, emoji: '🎂' },
  { re: /(^|[\s，。！、！?])(恭喜)(?=[\s，。！？!?]|$)/g, emoji: '🎉' },
  { re: /(^|[\s，。！、！?])(好运)(?=[\s，。！？!?]|$)/g, emoji: '🍀' }
];

/**
 * 把文字 emoji 别名 / 快捷词转成真实 emoji
 * @param {string} text 原始文本
 * @returns {string} 转换后的文本
 */
function convertEmoji(text) {
  if (!text) return '';
  let s = String(text);

  // 1) [别名] → emoji
  s = s.replace(/\[([^\]]+)\]/g, function (m, name) {
    const key = String(name).trim();
    return EMOJI_MAP[key] || m; // 表里没有就原样保留
  });

  // 2) 快捷词 → emoji（前插）
  WORD_EMOJI.forEach(function (w) {
    s = s.replace(w.re, function (match, pre, word) {
      return pre + w.emoji + word;
    });
  });

  return s;
}

